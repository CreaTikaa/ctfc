"""Turn a session into one script that re-does the whole solve.

A session already records every command and, for each one, the standalone
snippet that reproduces its result (`Candidate.python`). `ctfc report` renders
that as a write-up to read. This renders it as a **program to run**.

Why that is worth having as well: a write-up proves you solved it, a script
proves it *stays* solved. Paste the script next to the challenge files and the
whole chain runs again - which is what you want when the same ciphertext turns
up in the next round with a different key, when a teammate asks how, or when you
want to check that the thing you did at two in the morning actually works.

The blocks are simply concatenated, in order, each one preceded by the command
that produced it. Every snippet ctfc generates is self-contained - it defines
its own `data` and its own helpers - so concatenating them produces a file that
runs top to bottom with no editing. Re-defining a helper is legal in Python and
each block uses its own, so the duplication is harmless rather than clever.
"""

from __future__ import annotations

from ctfc.core.session import Entry, Session

HEADER = '''"""{title}

Re-does the whole solve, step by step. Generated by `ctfc replay` from the
session {name!r} ({steps} step(s) recorded{flag}).

Each block below is standalone: it defines its own input and its own helpers, so
the file runs top to bottom. The command that produced each one is quoted above
it - run that to see the reasoning again, with the scores and the reasons.
"""
'''
NO_SNIPPET = (
    "# This step produced no reproduce snippet: it was a report rather than a\n"
    "# transformation ({tool}). The command is above; run it to see the output."
)


def _flag_of(session: Session) -> str:
    """The flag the session settled on, if any."""
    meta = session.meta()
    if meta.flag:
        return meta.flag
    for entry in session.entries():
        for flag in entry.result.get("flags") or []:
            return str(flag)
    return ""


def _blocks(entries: list[Entry]) -> list[tuple[Entry, str]]:
    """The steps worth putting in the script, with their snippet.

    A session records notes and repeated commands too. Only steps are kept, and
    only the first of a run of identical snippets - re-running the same decoding
    twice in the script says nothing the first one did not.
    """
    out: list[tuple[Entry, str]] = []
    seen: set[str] = set()
    for entry in entries:
        if entry.kind != "step":
            continue
        snippet = (entry.result.get("python") or "").strip()
        if snippet and snippet in seen:
            continue
        if snippet:
            seen.add(snippet)
        out.append((entry, snippet))
    return out


def build_script(session: Session, include_empty: bool = False) -> str:
    """The session as a runnable Python script."""
    meta = session.meta()
    blocks = _blocks(session.entries())
    if not include_empty:
        blocks = [(entry, snippet) for entry, snippet in blocks if snippet]
    flag = _flag_of(session)
    out = [
        HEADER.format(
            title=meta.display_title(),
            name=meta.name,
            steps=len(blocks),
            flag=f", flag {flag}" if flag else "",
        )
    ]
    if not blocks:
        out.append(
            "# This session recorded no step with a reproduce snippet yet.\n"
            "# Run a command with a session active (ctfc session use <name>) and\n"
            "# the script will have something to replay.\n"
        )
        return "\n".join(out)

    for number, (entry, snippet) in enumerate(blocks, start=1):
        header = [f"# --- step {number}: {entry.tool or 'ctfc'} " + "-" * 40]
        if entry.command:
            header.append(f"# $ {entry.command}")
        source = entry.input.get("name") or entry.input.get("saved_as")
        if source:
            header.append(f"# input: {source} ({entry.input.get('size', '?')} bytes)")
        label = entry.result.get("label")
        if label:
            header.append(f"# result: {label}")
        for reason in (entry.result.get("reasons") or [])[:3]:
            header.append(f"#   - {reason}")
        out.append("\n".join(header))
        out.append(snippet if snippet else NO_SNIPPET.format(tool=entry.tool or "ctfc"))
        out.append("")

    if flag:
        out.append(f"# The flag this session found: {flag}")
    return "\n".join(out)
